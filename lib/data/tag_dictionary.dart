/// Checks whether a raw or namespaced tag belongs to the 18+ (NSFW) category.
bool isWdTagNsfw(String rawTag) {
  String clean = rawTag.contains(':') ? rawTag.split(':')[1] : rawTag;
  clean = clean.trim().toLowerCase();
  if (kNsfwExactTags.contains(clean)) return true;
  const extraSet = {
    'ass',
    'thighs',
    'thick_thighs',
    'bra',
    'leotard',
    'corset',
    'latex',
    'bodysuit',
    'blush',
    'navel',
  };
  if (extraSet.contains(clean)) return true;
  for (final sub in kNsfwSubstrings) {
    if (clean.contains(sub)) return true;
  }
  return false;
}

/// Translates any tag (including detail:, angle:, pose:, nsfw:, char:) to Russian.
/// Mirrors `translate_single_tag_ru` from `kokekbooru.py`.
String translateSingleTagRu(String rawTag, {Map<String, String>? dbCache}) {
  if (rawTag.trim().isEmpty) return '';
  final clean = rawTag.trim();
  String ns = '';
  String shortTag = clean;
  if (clean.contains(':')) {
    final idx = clean.indexOf(':');
    ns = clean.substring(0, idx);
    shortTag = clean.substring(idx + 1);
  }
  final shortLow = shortTag.toLowerCase().trim();

  if (ns == 'char') {
    return shortTag
        .split('_')
        .where((s) => s.isNotEmpty)
        .map((s) => s[0].toUpperCase() + s.substring(1))
        .join(' ');
  }

  if (dbCache != null) {
    if (dbCache.containsKey(clean.toLowerCase())) {
      return dbCache[clean.toLowerCase()]!;
    }
    if (dbCache.containsKey(shortLow)) {
      return dbCache[shortLow]!;
    }
  }

  if (kTagRuDict.containsKey(shortLow)) {
    return kTagRuDict[shortLow]!;
  }

  final noParen = shortLow.replaceAll(RegExp(r'_\(.*?\)'), '');
  if (kTagRuDict.containsKey(noParen)) {
    return kTagRuDict[noParen]!;
  }

  final parts = noParen.split('_').where((p) => p.isNotEmpty).toList();
  if (parts.isNotEmpty) {
    final translatedParts = <String>[];
    bool anyTranslated = false;
    int i = 0;
    while (i < parts.length) {
      if (i + 1 < parts.length) {
        final pair = '\${parts[i]}_\${parts[i + 1]}';
        if (kTagRuDict.containsKey(pair)) {
          translatedParts.add(kTagRuDict[pair]!.toLowerCase());
          anyTranslated = true;
          i += 2;
          continue;
        }
        if (kWordRuParts.containsKey(pair)) {
          translatedParts.add(kWordRuParts[pair]!);
          anyTranslated = true;
          i += 2;
          continue;
        }
      }
      final w = parts[i];
      if (kWordRuParts.containsKey(w)) {
        translatedParts.add(kWordRuParts[w]!);
        anyTranslated = true;
      } else if (kTagRuDict.containsKey(w)) {
        translatedParts.add(kTagRuDict[w]!.toLowerCase());
        anyTranslated = true;
      } else {
        translatedParts.add(w);
      }
      i += 1;
    }
    if (anyTranslated) {
      final res = translatedParts.join(' ').trim();
      if (res.isNotEmpty) {
        return res[0].toUpperCase() + res.substring(1);
      }
    }
  }

  return shortTag.replaceAll('_', ' ');
}
